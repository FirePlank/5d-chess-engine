// Cross-check `ktools rules` output against the reference implementation (ref5d.mjs),
// 5d-chess-js (js5d.cjs) and 5DC OL (col5d.mjs).
//
// usage: node --experimental-transform-types compare.mjs <ktools-rules-output> [options]
//   --actions        compare legal-action sets (Kairos `a` lines vs exhaustive reference search)
//   --mate-only      only check Kairos's mate status with a reference search for any legal action
//   --budget N       node budget of the reference action search (default 200000)
//   --col-mate       also run 5dcol's checkmate detection
//   --js-mate        also run 5d-chess-js's checkmate/stalemate detection (slow)
//   --no-js / --no-col   skip an implementation
//   --show N         print up to N examples per discrepancy kind (default 5)

import fs from 'node:fs'
import { createRequire } from 'node:module'
import * as ref from './ref5d.mjs'

const require = createRequire(import.meta.url)
const args = process.argv.slice(2)
const file = args[0]
const flag = (f) => args.includes(f)
const opt = (f, d) => (args.includes(f) ? Number(args[args.indexOf(f) + 1]) : d)
const BUDGET = opt('--budget', 200000)
const SHOW = opt('--show', 5)
const js5d = flag('--no-js') ? null : require('./js5d.cjs')
const col5d = flag('--no-col') ? null : await import('./col5d.mjs')
if (flag('--brawn-5dcol')) ref.OPTIONS.brawn = 'none'

function* records(text) {
  let rec = null
  for (const line of text.split(/\r?\n/)) {
    if (line.startsWith('G ')) {
      if (rec) yield rec
      rec = { G: line, B: [], m: [], k: [], a: [] }
    } else if (!rec) continue
    else if (line.startsWith('I ')) {
      const w = line.split(' ')
      const get = (name, n = 1) => w.slice(w.indexOf(name) + 1, w.indexOf(name) + 1 + n).map(Number)
      const [W, H] = get('size', 2)
      rec.I = { player: get('player')[0], present: get('present')[0], even: get('even')[0] === 1, W, H, promo: get('promo')[0] }
    } else if (line.startsWith('B ')) {
      const [, l, t, c, fen] = line.split(' ')
      rec.B.push([Number(l), Number(t), Number(c), fen])
    } else if (line.startsWith('T ')) rec.T = line
    else if (line.startsWith('m ')) rec.m.push(line.slice(2))
    else if (line.startsWith('k ')) rec.k.push(line.slice(2))
    else if (line.startsWith('C ')) rec.C = Number(line.slice(2))
    else if (line.startsWith('M ')) {
      const [, mate, n] = line.split(' ')
      rec.M = { mate, n: Number(n) }
    } else if (line.startsWith('a ')) rec.a.push(line.slice(2))
    else if (line.startsWith('E ')) rec.E = line
  }
  if (rec) yield rec
}

const diffs = new Map()
let positions = 0
function report(kind, rec, detail) {
  if (!diffs.has(kind)) diffs.set(kind, [])
  diffs.get(kind).push({ G: rec.G, detail })
}
// Prefix a move "l,t,x,y>..." with the letter of the piece that makes it (side to move = c).
function tagMove(pos, mk, c) {
  const [l, t, x, y] = mk.split('>')[0].split(',').map(Number)
  const b = pos && pos.board(l, 2 * t + c)
  return b ? `${b.get(x, y)}${b.unmoved(x, y) ? '*' : ''} ${mk}` : mk
}
function setDiff(kind, rec, mine, theirs, pos = null, c = 0) {
  const a = new Set(mine), b = new Set(theirs)
  const onlyK = [...a].filter((x) => !b.has(x)).map((m) => tagMove(pos, m, c))
  const onlyO = [...b].filter((x) => !a.has(x)).map((m) => tagMove(pos, m, c))
  if (onlyK.length || onlyO.length) report(kind, rec, { onlyKairos: onlyK.slice(0, 20), onlyOther: onlyO.slice(0, 20), nK: onlyK.length, nO: onlyO.length })
}

// Apply a Kairos action (moves "l,t,x,y>l,t,x,y") in the reference, resolving each move
// against the reference's own move list so special moves carry their side effects.
function applyAction(pos, action) {
  let p = pos
  for (const mk of action.split(' ')) {
    const m = ref.allMoves(p).find((x) => ref.moveKey(x) === mk)
    if (!m) return { error: `move ${mk} not generated by reference` }
    p = ref.applyMove(p, m)
  }
  if (!p.canSubmit()) return { error: 'cannot submit' }
  const after = ref.submit(p)
  if (ref.royalCaptures(after, after.player).length) return { error: 'leaves a royal capturable' }
  return { key: after.key() }
}

const stats = { actionsCompared: 0, actionsSkipped: 0, mateChecked: 0, mateUnknown: 0 }
const text = fs.readFileSync(file, 'utf8')
const t0 = Date.now()
for (const rec of records(text)) {
  if (rec.E) { report('kairos-parse-error', rec, rec.E); continue }
  positions++
  const pos = ref.positionFromRecord(rec)
  // Pseudo-legal moves.
  const me = pos.player, opp = 1 - pos.player
  setDiff('moves:ref', rec, rec.m, ref.allMoves(pos).map(ref.moveKey), pos, me)
  if (js5d) setDiff('moves:5d-chess-js', rec, rec.m, js5d.moves(pos), pos, me)
  if (col5d) setDiff('moves:5dcol', rec, rec.m, col5d.moves(pos), pos, me)
  // Checks against the side to move after passing on the mandatory boards.
  const refChecks = ref.phantomChecks(pos).map(ref.moveKey)
  setDiff('checks:ref', rec, rec.k, refChecks, pos, opp)
  if ((rec.k.length > 0) !== (rec.C === 1)) report('kairos-internal:C-vs-k', rec, { C: rec.C, k: rec.k.length })
  if (js5d) setDiff('checks:5d-chess-js', rec, rec.k, js5d.checks(pos), pos, opp)
  if (col5d) {
    setDiff('checks:5dcol-mandatory-pass', rec, rec.k, col5d.checksMandatory(pos), pos, opp)
    const colChecks = col5d.checks(pos)
    if ((colChecks.length > 0) !== (rec.C === 1)) report('incheck:5dcol-phantom', rec, { kairos: rec.C, col: colChecks.slice(0, 10) })
  }
  if (positions % 50 === 0) process.stderr.write(`.. ${positions} positions ${((Date.now() - t0) / 1000).toFixed(0)}s
`)
  // Mate status only: search for any legal action (stops at the first one).
  if (flag('--mate-only') && rec.M) {
    const r = ref.legalActions(pos, { budget: BUDGET, stopAtFirst: true })
    const refMate = r.results.size > 0 ? 'none' : r.complete ? (refChecks.length ? 'checkmate' : 'stalemate') : null
    if (refMate === null) { stats.mateUnknown++; report('mate:ref-unknown', rec, { kairos: rec.M.mate, nodes: r.nodes }) }
    else {
      stats.mateChecked++
      const k = rec.M.mate === 'softmate' ? 'none' : rec.M.mate
      if (k !== refMate) report('mate:ref', rec, { kairos: rec.M.mate, ref: refMate, action: [...r.results.values()][0]?.map(ref.moveKey) })
    }
  }
  // Legal actions and mate status.
  if (flag('--actions') && rec.M) {
    const kairosComplete = rec.M.n < opt('--cap', Infinity)
    const r = ref.legalActions(pos, { budget: BUDGET })
    const kKeys = []
    for (const a of rec.a) {
      const res = applyAction(pos, a)
      if (res.error) report('action:kairos-action-illegal-in-ref', rec, { action: a, error: res.error })
      else kKeys.push(res.key)
    }
    const dup = kKeys.length - new Set(kKeys).size
    if (dup) report('action:kairos-duplicate-results', rec, { dup })
    if (r.complete && kairosComplete) {
      stats.actionsCompared++
      const refKeys = [...r.results.keys()]
      const a = new Set(kKeys), b = new Set(refKeys)
      const missing = refKeys.filter((x) => !a.has(x))
      const extra = kKeys.filter((x) => !b.has(x))
      if (missing.length || extra.length)
        report('action:set-differs', rec, {
          kairos: kKeys.length, ref: refKeys.length, extra: extra.length,
          missingExamples: missing.slice(0, 3).map((k) => r.results.get(k).map(ref.moveKey).join(' ')),
        })
    } else stats.actionsSkipped++
    // Mate status.
    let refMate = null
    if (r.results.size > 0) refMate = 'none'
    else if (r.complete) refMate = refChecks.length ? 'checkmate' : 'stalemate'
    if (refMate === null && rec.M.mate !== 'none') {
      const r2 = ref.legalActions(pos, { budget: BUDGET * 10, stopAtFirst: true })
      if (r2.results.size > 0) refMate = 'none'
      else if (r2.complete) refMate = refChecks.length ? 'checkmate' : 'stalemate'
    }
    if (refMate === null && rec.M.mate === 'none' && kKeys.length > 0) refMate = 'none'
    if (refMate === null) stats.mateUnknown++
    else {
      stats.mateChecked++
      const k = rec.M.mate === 'softmate' ? 'none' : rec.M.mate
      if (k !== refMate) report('mate:ref', rec, { kairos: rec.M.mate, ref: refMate })
    }
  }
  if (flag('--col-mate') && col5d && rec.M) {
    const m = col5d.mate(pos)
    const k = rec.M.mate === 'softmate' ? 'none' : rec.M.mate
    const c = m.status === 'not-checkmate' ? 'none' : m.status
    if (k !== c) report('mate:5dcol', rec, { kairos: rec.M.mate, col: m.status, action: m.action })
  }
  if (flag('--js-mate') && js5d && rec.M) {
    const m = js5d.mate(pos)
    const k = rec.M.mate === 'softmate' ? 'none' : rec.M.mate
    const j = m.checkmate ? 'checkmate' : m.stalemate ? 'stalemate' : 'none'
    if (k !== j) report('mate:5d-chess-js', rec, { kairos: rec.M.mate, js: m })
  }
}

console.log(`positions ${positions} in ${((Date.now() - t0) / 1000).toFixed(1)}s ${JSON.stringify(stats)}`)
for (const [kind, list] of [...diffs].sort()) {
  console.log(`DIFF ${kind}: ${list.length} positions`)
  for (const d of list.slice(0, SHOW)) {
    console.log(`  ${d.G.length > 400 ? d.G.slice(0, 200) + ' ... ' + d.G.slice(-200) : d.G}`)
    console.log(`    ${JSON.stringify(d.detail)}`)
  }
}
if (process.env.DIFF_JSON) fs.writeFileSync(process.env.DIFF_JSON, JSON.stringify(Object.fromEntries(diffs), null, 1))
