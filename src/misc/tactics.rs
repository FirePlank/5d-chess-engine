//! Tactics regression suite (`data/tactics.g`): positions with known correct or wrong actions.
//! The suite is generated from `data/tactics_src.txt` by `ktools tacticsgen`.
//! A `mate <n>` position is also solved by any action proven to mate in `n` or fewer.

use crate::core::action::Action;
use crate::core::perft::parse_g_line;
use crate::core::state::{MateType, State};

/// One suite position.
pub struct Tactic {
    pub name: String,
    pub g: String,
    pub state: State,
    /// The correct actions (any of them solves the position), or with `avoid` the wrong ones.
    pub best: Vec<Action>,
    /// Their LAN, as in the file.
    pub best_lan: Vec<String>,
    /// `best` lists the actions to avoid: any other solves the position.
    pub avoid: bool,
    /// The correct actions force mate in this many actions (of the side to move).
    pub mate: Option<u32>,
}

impl Tactic {
    /// Whether playing `a` solves the position.
    pub fn solved_by(&self, a: &Action) -> bool {
        self.avoid != self.best.contains(a)
    }
}

/// Parse a suite file; every position and every best (or avoided) action is checked legal.
pub fn parse(text: &str) -> Result<Vec<Tactic>, String> {
    let mut out = Vec::new();
    let mut head: Option<(String, Option<u32>, Vec<String>, bool)> = None;
    for (n, line) in text.lines().enumerate() {
        let line = line.trim();
        let err = |e: String| format!("tactics line {}: {}", n + 1, e);
        if let Some(c) = line.strip_prefix("# ") {
            let split = c.split_once(" best ").map(|x| (x, false)).or_else(|| c.split_once(" avoid ").map(|x| (x, true)));
            if let Some(((name, rest), avoid)) = split {
                let rest = rest.split_once(" ; ").map_or(rest, |(a, _)| a);
                let (name, mate) = match name.rsplit_once(" mate ") {
                    Some((nm, k)) if k.trim().parse::<u32>().is_ok() => (nm, k.trim().parse().ok()),
                    _ => (name, None),
                };
                head = Some((name.trim().to_string(), mate, rest.split(" | ").map(|a| a.trim().to_string()).collect(), avoid));
            }
            continue;
        }
        if !line.starts_with("G ") {
            continue;
        }
        let (name, mate, lans, avoid) = head.take().ok_or_else(|| err("G line without a \"# <name> best <action>\" line".into()))?;
        let state = parse_g_line(line).map_err(err)?;
        let mut best = Vec::new();
        for lan in &lans {
            let moves = crate::web::tree::parse_lan_moves(lan).map_err(err)?;
            crate::web::tree::play_action(&state, &moves).map_err(|e| err(format!("{}: illegal best action {}: {}", name, lan, e)))?;
            best.push(Action::from_vector(&moves, &state));
        }
        out.push(Tactic { name, g: line.to_string(), state, best, best_lan: lans, avoid, mate });
    }
    Ok(out)
}

/// Every legal action of `s` that checkmates at once (at most `cap` actions are examined).
pub fn mates_in_one(s: &State, cap: usize) -> Vec<Action> {
    use crate::core::hypercuboid::HcInfo;
    let (w, ss) = HcInfo::build_hc(s);
    let mut out = Vec::new();
    for mv in w.search(s, ss).take(cap) {
        let a = Action::from_moveseq(&mv, s);
        if let Ok(next) = crate::web::tree::play_action(s, a.moves())
            && next.get_mate_type() == MateType::Checkmate && !out.contains(&a) {
                out.push(a);
            }
    }
    out
}

/// The suite file from its 5dpgn source (see the module docs). Notes about the correct
/// actions (mates in one replacing the source's action) go to `notes`.
pub fn generate_with_notes(src: &str, notes: &mut Vec<String>) -> Result<String, String> {
    use crate::core::variants::state_from_setup;
    use crate::web::pgn::{action_to_pgn, parse_5dpgn, parse_action};
    use crate::web::record::setup_to_uci;
    use crate::web::tree::{action_lan, play_action};
    let mut out = String::from(
        "# Tactics regression suite, generated by `ktools tacticsgen data/tactics_src.txt` (sources and\n\
         # notes there); do not edit by hand. Run with `ktools tactics [file] [ms] [threads]`.\n",
    );
    for (n, line) in src.lines().enumerate() {
        let line = line.trim();
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        let err = |e: String| format!("source line {}: {}", n + 1, e);
        let parts: Vec<&str> = line.split(" | ").collect();
        if parts.len() < 3 || parts.len() > 4 {
            return Err(err("expected \"<name> | <best> | <5dpgn> [| mate <n>]\"".into()));
        }
        let (name, best, pgn) = (parts[0].trim(), parts[1], parts[2]);
        let mate = match parts.get(3).map(|m| m.trim()) {
            None => None,
            Some(m) => Some(m.strip_prefix("mate ").and_then(|k| k.parse::<u32>().ok()).ok_or_else(|| err(format!("bad {:?}", m)))?),
        };
        let game = parse_5dpgn(pgn, None).map_err(err)?;
        let mut s = state_from_setup(&game.setup).map_err(err)?;
        let mut g = format!("G {} {} moves", game.setup.promotions.0, setup_to_uci(&game.setup));
        let mut node = &game.root;
        while let Some(child) = node.children.first() {
            let act = child.action.as_ref().ok_or_else(|| err("action missing".into()))?;
            for m in act.moves() {
                g += &format!(" {}", m);
            }
            g += " submit";
            s = play_action(&s, act.moves()).map_err(|e| err(format!("{}: {}", child.text, e)))?;
            node = child;
        }
        let (best, mut avoid) = match best.trim().strip_prefix("not ") {
            Some(b) => (b, true),
            None => (best, false),
        };
        let mut acts = Vec::new();
        for b in best.split(" or ") {
            let a = parse_action(&s, b.trim()).map_err(|e| err(format!("best {}: {}", b, e)))?;
            play_action(&s, a.moves()).map_err(|e| err(format!("best {}: {}", b, e)))?;
            acts.push(a);
        }
        let mut note = String::new();
        let mates = mates_in_one(&s, 20_000);
        let mate_in_one = !mates.is_empty();
        if mate_in_one {
            let given: Vec<String> = acts.iter().map(|a| action_to_pgn(&s, a)).collect();
            if acts.iter().any(|a| !mates.contains(a)) {
                note = format!(" ; mate in one replaces the source's {}", given.join(" or "));
                notes.push(format!("{}: mate in one replaces {}", name, given.join(" or ")));
            } else if mates.len() > acts.len() {
                notes.push(format!("{}: {} actions mate in one", name, mates.len()));
            }
            acts = mates;
            avoid = false;
        }
        let lans: Vec<String> = acts.iter().map(|a| action_lan(&s, a)).collect();
        let pgns: Vec<String> = acts.iter().map(|a| action_to_pgn(&s, a)).collect();
        // A mate in one: any checkmating action is listed, so no mate length is needed.
        let mate = if mate_in_one { None } else { mate };
        let mate_txt = mate.map(|k| format!(" mate {}", k)).unwrap_or_default();
        if avoid {
            out += &format!("# {}{} avoid {} ; not {}\n{}\n", name, mate_txt, lans.join(" | "), pgns.join(" | "), g);
        } else {
            out += &format!("# {}{} best {} ; {}{}\n{}\n", name, mate_txt, lans.join(" | "), pgns.join(" | "), note, g);
        }
    }
    Ok(out)
}

/// `generate_with_notes` without the notes.
pub fn generate(src: &str) -> Result<String, String> {
    generate_with_notes(src, &mut Vec::new())
}
